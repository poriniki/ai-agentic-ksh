#!/usr/bin/env node
'use strict';
/*
 * Writes the Persian pages (fa/index.html, fa/presenter.html, fa/join.html)
 * from the English pages, so there is one source for the markup.
 *
 *   - <html> gets lang="fa" dir="rtl", and data-base/data-join so the scripts
 *     reach the API and the audience page from the fa/ folder
 *   - asset paths move up one folder; the deck data becomes deck.fa.js
 *   - external font requests are dropped (Vazirmatn is self-hosted)
 *   - text of elements marked data-i18n="key", and attributes listed in
 *     data-i18n-attrs="attr:key;attr:key", come from assets/js/i18n.js
 *
 * Marked elements must contain plain text only (no child elements).
 *
 *   node tools/build-pages.js          write the pages
 *   require('./build-pages').render()  return them (used by check-deck.js)
 */
const fs = require('fs');
const path = require('path');

const WEB = path.resolve(__dirname, '..');
const OUT_DIR = path.join(WEB, 'fa');
const PAGES = ['index.html', 'presenter.html', 'join.html'];

function escapeHtml(s) {
  return String(s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function loadI18n() {
  const file = path.join(WEB, 'assets', 'js', 'i18n.js');
  delete require.cache[require.resolve(file)];
  const i18n = require(file);
  i18n.setLang('fa');
  return i18n;
}

function translateAttrs(tag, spec, i18n) {
  let out = tag;
  spec.split(';').map((p) => p.trim()).filter(Boolean).forEach((pair) => {
    const [attr, key] = pair.split(':').map((x) => x.trim());
    const value = escapeHtml(i18n.t(key));
    const re = new RegExp(`\\s${attr}="[^"]*"`);
    if (re.test(out)) out = out.replace(re, ` ${attr}="${value}"`);
    else out = out.replace(/\s*>$/, ` ${attr}="${value}">`);
  });
  return out;
}

function renderPage(name, i18n) {
  const src = fs.readFileSync(path.join(WEB, name), 'utf8');
  let html = src
    .replace(/<html lang="en"([^>]*)>/, '<html lang="fa" dir="rtl"$1 data-base="../" data-join="fa/join">')
    .replace(/(src|href)="(assets\/[^"]+)"/g, '$1="../$2"')
    .replace('src="data/deck.js"', 'src="../data/deck.fa.js"')
    .replace(/[ \t]*<link rel="preconnect"[^>]*>\n/g, '')
    .replace(/[ \t]*<link rel="stylesheet" href="https:\/\/fonts\.googleapis\.com[^>]*>\n/g, '');

  // Attributes first, on the opening tag that carries data-i18n-attrs.
  html = html.replace(/<[a-z0-9]+\b[^>]*\sdata-i18n-attrs="([^"]+)"[^>]*>/g, (tag, spec) => translateAttrs(tag, spec, i18n));

  // Then plain-text content of elements marked data-i18n.
  let translated = 0;
  html = html.replace(/(<([a-z0-9]+)\b[^>]*\sdata-i18n="([^"]+)"[^>]*>)([^<]*)(<\/\2>)/g, (m, open, tagName, key, text, close) => {
    const value = i18n.t(key);
    if (typeof value !== 'string' || value === key) throw new Error(`${name}: no Persian text for "${key}"`);
    translated += 1;
    return open + escapeHtml(value) + close;
  });
  const marked = (src.match(/\sdata-i18n="/g) || []).length;
  if (translated !== marked) {
    throw new Error(`${name}: ${marked - translated} element(s) marked data-i18n contain markup; keep them text-only`);
  }

  return html.replace('<!doctype html>\n', '<!doctype html>\n<!-- Generated by tools/build-pages.js from ../' + name + '. Edit that file, then run "npm run build". -->\n');
}

function render() {
  const i18n = loadI18n();
  const out = {};
  PAGES.forEach((name) => { out[name] = renderPage(name, i18n); });
  return out;
}

function write() {
  fs.mkdirSync(OUT_DIR, { recursive: true });
  const pages = render();
  Object.keys(pages).forEach((name) => fs.writeFileSync(path.join(OUT_DIR, name), pages[name]));
  return Object.keys(pages);
}

module.exports = { render, write, OUT_DIR, PAGES };

if (require.main === module) {
  const written = write();
  console.log(`Wrote fa/${written.join(', fa/')}`);
}
